SCHEMA_SQL = """
CREATE TABLE departments (
  dept_id   INTEGER PRIMARY KEY,
  dept_name TEXT NOT NULL,
  location  TEXT
);

CREATE TABLE employees (
  emp_id    INTEGER PRIMARY KEY,
  name      TEXT NOT NULL,
  gender    TEXT,
  age       INTEGER,
  dept_id   INTEGER,
  salary    REAL,
  hire_date TEXT
);

CREATE TABLE products (
  product_id   INTEGER PRIMARY KEY,
  product_name TEXT NOT NULL,
  category     TEXT,
  price        REAL,
  stock        INTEGER
);

CREATE TABLE orders (
  order_id      INTEGER PRIMARY KEY,
  customer_name TEXT,
  product_id    INTEGER,
  quantity      INTEGER,
  order_date    TEXT,
  amount        REAL
);

CREATE TABLE students (
  student_id INTEGER PRIMARY KEY,
  name       TEXT,
  class      TEXT,
  gender     TEXT
);

CREATE TABLE scores (
  score_id   INTEGER PRIMARY KEY,
  student_id INTEGER,
  subject    TEXT,
  score      INTEGER
);
"""

